export function registerTranslations(): void {
  Language.addTranslations("en", EN);
  Language.addTranslations("zh", ZH);
}

export function isChineseOnlyBuild(): boolean {
  return typeof __DAP_FORCE_LANGUAGE__ !== "undefined" && __DAP_FORCE_LANGUAGE__ === "zh";
}

export function tr(key: string, replacements: Replacements = {}): string {
  const forcedLanguage =
    typeof __DAP_FORCE_LANGUAGE__ === "undefined" ? null : __DAP_FORCE_LANGUAGE__;
  let text = forcedLanguage === "zh" ? ZH[key] ?? EN[key] ?? key : tl(key);
  if (text === key) text = EN[key] ?? key;
  for (const [name, value] of Object.entries(replacements)) {
    text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}
